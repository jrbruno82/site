function formatMilk(value) {
  return value ? `${value.toLocaleString(locale())} ${t("milkUnit")}` : "—";
}

function formatPercentage(value) {
  return new Intl.NumberFormat(locale(), { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(value);
}

function bullPhoto(bull) {
  return `<span class="bull-photo" style="background:${bull.color}"><span class="bull-initial">${bull.initials}</span></span>`;
}

function getVisibleBulls() {
  let result = bulls.filter((bull) => {
    const matchesBreed = state.breed === "Todas" || bull.breed === state.breed;
    const matchesElite = !state.eliteOnly || bull.elite;
    const matchesFavorite = !state.favoritesOnly || favorites.has(bull.id);
    const query = state.search.trim().toLocaleLowerCase(locale());
    const matchesSearch = !query || [bull.name, bull.id, bull.breed, localizeBreed(bull.breed)].some((value) => value.toLocaleLowerCase(locale()).includes(query));
    return matchesBreed && matchesElite && matchesFavorite && matchesSearch;
  });

  if (state.sort === "milk") result.sort((a, b) => b.milk - a.milk);
  if (state.sort === "name") result.sort((a, b) => a.name.localeCompare(b.name, locale()));
  if (state.sort === "ranking") result.sort((a, b) => b.index - a.index);
  return result;
}

