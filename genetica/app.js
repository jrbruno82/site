function comparisonValue(bull) {
  const metric = document.querySelector("#comparison-metric").value;
  const values = {
    index: { raw: bull.index, display: bull.index.toLocaleString(locale()) },
    milk: { raw: bull.milk, display: formatMilk(bull.milk) },
    protein: { raw: bull.protein, display: `${formatPercentage(bull.protein)}%` },
    fat: { raw: bull.fat, display: `${formatPercentage(bull.fat)}%` },
    confidence: { raw: bull.confidence, display: `${bull.confidence}%` },
  };
  return values[metric];
}

function renderComparison() {
  const selected = bulls.filter((bull) => selectedForComparison.has(bull.id));
  const chart = document.querySelector("#comparison-chart");
  if (!selected.length) {
    chart.innerHTML = `<p class="comparison-empty">${t("comparisonEmpty")}</p>`;
    return;
  }
  const values = selected.map((bull) => ({ bull, ...comparisonValue(bull) }));
  const maxValue = Math.max(...values.map((entry) => entry.raw), 1);
  chart.innerHTML = values.map(({ bull, raw, display }) => `
    <div class="comparison-row">
      <span class="comparison-bull">${bull.name} · ${localizeBreed(bull.breed)}</span>
      <span class="comparison-bar-track" role="img" aria-label="${display}">
        <span class="comparison-bar" style="width:${Math.max(raw / maxValue * 100, raw ? 2 : 0)}%"></span>
      </span>
      <strong class="comparison-value">${display}</strong>
    </div>
  `).join("");
}

function escapeHtml(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]);
}

